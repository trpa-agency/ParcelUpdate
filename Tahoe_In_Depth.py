def _clean_name(name: str) -> str:
    """
    Normalize a name for dedup comparison only (not for display):
    - Uppercase
    - Strip punctuation (apostrophes, periods, hyphens, etc.)
    - Collapse MC DONALD → MCDONALD, MAC DONALD → MACDONALD
    - Normalize legal entity suffixes to canonical short forms
    - Collapse extra spaces
    """
    s = name.upper()
    # #11 — remove apostrophes before stripping all punctuation so O'BRIEN→OBRIEN
    s = s.replace("'", "")
    # Strip all remaining non-alphanumeric except spaces
    s = re.sub(r'[^A-Z0-9 ]', '', s)
    s = re.sub(r'\s+', ' ', s).strip()
    # #11 — collapse "MC " / "MAC " prefix compounding
    s = re.sub(r'\bMC\s+([A-Z])', r'MC\1', s)
    s = re.sub(r'\bMAC\s+([A-Z])', r'MAC\1', s)
    # #10 — normalize legal entity suffixes
    s = re.sub(r'\bLIMITED\s+LIABILITY\s+COMPANY\b', 'LLC', s)
    s = re.sub(r'\bL\s*L\s*C\b', 'LLC', s)
    s = re.sub(r'\bLIMITED\s+PARTNERSHIP\b', 'LP', s)
    s = re.sub(r'\bL\s*P\b', 'LP', s)
    s = re.sub(r'\bINCORPORATED\b', 'INC', s)
    s = re.sub(r'\bCORPORATION\b', 'CORP', s)
    s = re.sub(r'\bFAMILY\s+TRUST\b', 'TRUST', s)
    s = re.sub(r'\bFAM\s+TRUST\b', 'TRUST', s)
    s = re.sub(r'\bFAM\s+TR\b', 'TRUST', s)
    s = re.sub(r'\bTRUSTEES?\b', 'TR', s)
    s = re.sub(r'\bLIMITED\b', 'LTD', s)
    return re.sub(r'\s+', ' ', s).strip()



def flag_duplicates(df: pd.DataFrame) -> pd.DataFrame:
    """
    Flags duplicate records using three keys. All occurrences are flagged
    (first row included) so the full group is visible in Sheet 1.

    Key 1 — STD_STREET + STD_ZIP
    Key 2 — STD_STREET + STD_CITY
    Key 3 — left 10 chars of cleaned OwnerName + STD_STREET
    """
    df = df.copy()

    owner_col = "OwnerName" if "OwnerName" in df.columns else None
    cleaned   = df[owner_col].apply(lambda x: _clean_name(str(x)) if x else "") \
                if owner_col else pd.Series("", index=df.index)

    # ── Key 1: STD_STREET + STD_ZIP ────────────────────────────────────
    key1       = df["STD_STREET"] + "|" + df["STD_ZIP"]
    valid_key1 = (df["STD_STREET"] != "") & (df["STD_ZIP"] != "")
    mask1      = valid_key1 & key1.duplicated(keep=False)

    # ── Key 2: STD_STREET + STD_CITY ───────────────────────────────────
    key2       = df["STD_STREET"] + "|" + df["STD_CITY"]
    valid_key2 = (df["STD_STREET"] != "") & (df["STD_CITY"] != "")
    mask2      = valid_key2 & key2.duplicated(keep=False)

    # ── Key 3: left 10 chars of name + STD_STREET ──────────────────────
    name10     = cleaned.str[:10]
    key3       = name10 + "|" + df["STD_STREET"]
    valid_key3 = (name10 != "") & (df["STD_STREET"] != "")
    mask3      = valid_key3 & key3.duplicated(keep=False)

    def build_reason(row_idx):
        reasons = []
        if mask1.iloc[row_idx]: reasons.append("Street+ZIP")
        if mask2.iloc[row_idx]: reasons.append("Street+City")
        if mask3.iloc[row_idx]: reasons.append("Name+Street")
        return "; ".join(reasons)

    reasons = [build_reason(i) for i in range(len(df))]
    df["IS_DUPLICATE"] = ["YES" if r else "NO" for r in reasons]
    df["DUPE_REASON"]  = reasons

    reason_counts = df["REASON"].map(df["REASON"].value_counts())
    df.insert(df.columns.get_loc("REASON") + 1, "REASON_COUNT", reason_counts)

    return df

