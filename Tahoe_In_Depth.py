def clean_str(val) -> str:
    """Trim, collapse all internal whitespace, uppercase. Returns '' for null."""
    if val is None or (isinstance(val, float) and pd.isna(val)):
        return ""
    s = str(val).strip()
    s = re.sub(r'\s+', ' ', s)
    return s.upper()


def apply_replacements(text: str, mapping: dict) -> str:
    for pattern, replacement in mapping.items():
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text


def standardize_po_box(address: str) -> str:
    """Normalize all PO Box variants → 'PO BOX {number}'."""
    m = re.match(
        r'^(?:P\.?\s*O\.?\s*B?\.?\s*|POST\s+OFFICE\s+)?(?:BOX\s+)(\d+)',
        address, re.IGNORECASE
    )
    if m:
        return f"PO BOX {m.group(1)}"
    m2 = re.match(r'^P\.?O\.?\s+(\d+)$', address, re.IGNORECASE)
    if m2:
        return f"PO BOX {m2.group(1)}"
    return address


def strip_care_of(address: str) -> str:
    """
    Remove 'C/O ...', 'ATTN: ...', 'ATTN ...', 'IN CARE OF ...' and everything
    that follows, preserving any street/unit info before the marker.

    Uses a capture-group approach so it fires even when C/O is jammed directly
    against a digit or letter with no space (e.g. '890C/O TRUST').

    Examples:
      1001 TAHOE BLVD C/O ZAZOVE ASSOCIATES          -> 1001 TAHOE BLVD
      101 CALIFORNIA ST STE 2500 ATTN: BESSEMER      -> 101 CALIFORNIA ST STE 2500
      1017 WINDING WAY C/O JULIA NICKLES BRYAN       -> 1017 WINDING WAY
      101 WESTCOTT ST APT 603 C/O NANCY CHANG        -> 101 WESTCOTT ST APT 603
      100 W LIBERTY ST STE 890 C/O WHITTIER TRUST    -> 100 W LIBERTY ST STE 890
      100 W LIBERTY ST STE 890C/O WHITTIER TRUST     -> 100 W LIBERTY ST STE 890
    """
    pattern = re.compile(
        r'^(.*?)\s*(?:C/O|ATTN\.?:?|IN\s+CARE\s+OF|CARE\s+OF)(?:\s|$).*$',
        re.IGNORECASE | re.DOTALL
    )
    m = pattern.match(address)
    if m:
        return m.group(1).strip()
    return address.strip()


def standardize_street(raw: str) -> str:
    if not raw:
        return raw
    s = clean_str(raw)  # uppercase + collapsed whitespace

    if re.match(r'^(?:P\.?\s*O\.?\s*|POST\s+OFFICE\s+|BOX\s+)', s):
        return standardize_po_box(s)

    # First pass: strip before suffix substitution so names like
    # 'ASSOCIATES', 'TRUST', 'WAY' in a person's name don't get mangled.
    s = strip_care_of(s)

    # Strip periods from abbreviated directionals and suffixes so that
    # "W." → "W" and "ST." → "ST" before the maps run.
    # Matches a word made of 1-4 letters followed by a period (word boundary).
    s = re.sub(r'\b([A-Z]{1,4})\.(?=\s|$)', r'\1', s)

    s = apply_replacements(s, DIRECTIONAL_MAP)
    s = apply_replacements(s, STREET_SUFFIX_MAP)
    s = apply_replacements(s, UNIT_DESIGNATOR_MAP)
    s = apply_replacements(s, ORDINAL_MAP)

    # Second pass: catch anything that survived the replacements above.
    s = strip_care_of(s)

    result = re.sub(r'\s+', ' ', s).strip()

    # Safety net: if stripping C/O left nothing, keep the original value
    return result if result else clean_str(raw)


def apply_city_correction(raw: str) -> str:
    """
    1. Apply manual corrections from CITY_CORRECTIONS (exact match).
    2. If not found and the city is not already a known canonical city,
       attempt fuzzy matching against KNOWN_CITIES using difflib.
       Only accepts matches with cutoff >= 0.88 and a single close match
       (to avoid false positives).
    Input should already be uppercase and whitespace-collapsed.
    """
    corrected = CITY_CORRECTIONS.get(raw, raw)
    if corrected != raw:
        return corrected
    # Skip fuzzy check if city is already a known valid city
    if raw in KNOWN_CITIES:
        return raw
    matches = difflib.get_close_matches(raw, KNOWN_CITIES, n=1, cutoff=0.88)
    if matches:
        return matches[0]
    return raw


def clean_owner_name(raw: str) -> str:
    """
    Strip 'C/O ...' and 'ATTN ...' suffixes from owner names using
    the same pattern as strip_care_of() for streets.

    Examples:
      1050 LAKE VISTA LLC C/O RYAN NICHOLS   -> 1050 LAKE VISTA LLC
      1345 WOODLAND WAY LLC C/O DOUG VANESKO -> 1345 WOODLAND WAY LLC
      SMITH JOHN                             -> SMITH JOHN  (unchanged)
    """
    if not raw:
        return raw
    pattern = re.compile(
        r'^(.*?)\s*(?:C/O|ATTN\.?:?|IN\s+CARE\s+OF|CARE\s+OF)(?:\s|$).*$',
        re.IGNORECASE | re.DOTALL
    )
    m = pattern.match(raw)
    if m:
        result = m.group(1).strip()
        return result if result else raw
    return raw


def standardize_city(raw: str) -> str:
    """Uppercase and collapse whitespace."""
    return re.sub(r'\s+', ' ', raw.upper().strip())


def apply_zip_city_override(city: str, zip5: str) -> tuple:
    """
    If zip5 is in ZIP_CITY_OVERRIDES, return the correct city and a note.
    Otherwise return the city unchanged with no note.

    Returns (corrected_city, override_note)
      override_note is non-empty only when a correction was made, e.g.:
      'ZIP override 89448: ZEPHYR COVE NV -> ZEPHYR COVE'
    """
    if zip5 in ZIP_CITY_OVERRIDES:
        correct = ZIP_CITY_OVERRIDES[zip5]
        if city != correct:
            note = f'ZIP override {zip5}: {city} -> {correct}'
            return correct, note
    return city, ''

def split_street(std: str) -> tuple:
    """
    Split a standardized street value into (street1, street2).
    If the value contains both a physical address and a PO BOX, the PO BOX
    goes into street2 and everything else into street1.
    If there is only one component, street1 = std and street2 = "".

    Examples:
      "1 BIG WATER DR #A201 PO BOX 1155"  -> ("1 BIG WATER DR #A201", "PO BOX 1155")
      "PO BOX 1155 1 BIG WATER DR"        -> ("1 BIG WATER DR", "PO BOX 1155")
      "PO BOX 42"                         -> ("PO BOX 42", "")
      "123 MAIN ST"                       -> ("123 MAIN ST", "")
    """
    po_pattern = re.compile(
        r'(P\.?\s*O\.?\s*BOX\s+\S+)', re.IGNORECASE
    )
    m = po_pattern.search(std)
    if m:
        po_part  = m.group(1).strip()
        remainder = (std[:m.start()] + std[m.end():]).strip()
        if remainder:
            return remainder, po_part
        # Only a PO BOX, no physical address
        return po_part, ""
    return std, ""


def standardize_state(raw: str) -> str:
    s = raw.upper().strip()
    if s in VALID_STATES:
        return s
    return STATE_NAME_MAP.get(s, s)


def standardize_zip(raw: str) -> str:
    """Keep only the 5-digit ZIP, zero-padded. Strips ZIP+4 extension (e.g. 92660-2845 -> 92660).
    Pads short ZIPs with leading zeros so 6232 -> 06232."""
    s = re.sub(r'[^0-9]', '', raw.strip())  # digits only
    s = s[:5] if len(s) >= 5 else s         # take first 5 digits
    return s.zfill(5) if s else s            # zero-pad to 5 digits

