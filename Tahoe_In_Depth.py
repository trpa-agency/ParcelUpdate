def validate_row(street: str, city: str, state: str, zip_code: str):
    """Returns (STATUS, REASON). First failure wins."""
    st = clean_str(street)
    ct = clean_str(city)
    s  = clean_str(state)
    zp = clean_str(zip_code)

    # Street
    if not st:
        return "INVALID", "No Street"
    if st in PLACEHOLDER_STREETS:
        return "INVALID", "Invalid Street"

    # City
    if not ct:
        return "INVALID", "No City"

    # State
    if not s:
        return "INVALID", "No State"
    resolved = STATE_NAME_MAP.get(s, s)
    if resolved not in VALID_STATES:
        return "INVALID", "Invalid State"

    # ZIP — validate and compare on 5-digit ZIP only (ignores +4 extension)
    if not zp:
        return "INVALID", "Missing ZIP"
    digits_only = re.sub(r'[^0-9]', '', zp)   # strip all non-digits
    zip5 = digits_only[:5]                      # take first 5 digits
    if len(zip5) < 5 or not zip5.isdigit():
        return "INVALID", "Invalid ZIP Format"
    if zip5.startswith("000"):
        return "INVALID", "Invalid ZIP Prefix"

    # Check 1 — ZIP prefix vs state (all 50 states)
    prefix = int(zip5[:3])
    valid_for_prefix = PREFIX_TO_STATES.get(prefix, set())
    if valid_for_prefix and resolved not in valid_for_prefix:
        return "INVALID", "State/ZIP Mismatch"

    # Checks 2 & 3 — exact ZIP existence + city match (CA and NV only)
    if resolved in ("CA", "NV"):
        zip_entry = CA_NV_ZIP_LOOKUP.get(zip5)

        # Check 2: exact ZIP must exist
        if zip_entry is None:
            return "INVALID", f"ZIP {zip5} not valid for {resolved}"

        # Check 3: city must match the canonical city for that ZIP (or an allowed alternate)
        # Apply ZIP override first so overridden cities pass the mismatch check
        ct_for_check, _ = apply_zip_city_override(ct, zip5)
        canonical_city, _ = zip_entry
        additional = ZIP_ADDITIONAL_CITIES.get(zip5, set())
        if ct_for_check and ct_for_check != canonical_city and ct_for_check not in additional:
            return "INVALID", f"City/ZIP Mismatch: {ct} not in ZIP {zip5} ({canonical_city})"

    return "VALID", ""

