def load_from_sql() -> pd.DataFrame:
    auth_mode = "Windows Authentication" if USE_WINDOWS_AUTH else f"SQL login ({SQL_USERNAME})"
    print(f"Connecting to {SQL_SERVER} / {SQL_DATABASE} using {auth_mode} ...")

    if not USE_WINDOWS_AUTH and (not SQL_USERNAME or not SQL_PASSWORD):
        raise ValueError(
            "USE_WINDOWS_AUTH is False but SQL_USERNAME or SQL_PASSWORD is empty.\n"
            "Fill in both credentials at the top of the script, or set USE_WINDOWS_AUTH = True."
        )

    drivers = [
        "ODBC Driver 17 for SQL Server",
        "ODBC Driver 18 for SQL Server",
        "SQL Server",
    ]
    conn = None
    for driver in drivers:
        try:
            if USE_WINDOWS_AUTH:
                conn_str = (
                    f"DRIVER={{{driver}}};"
                    f"SERVER={SQL_SERVER};"
                    f"DATABASE={SQL_DATABASE};"
                    f"Trusted_Connection=yes;"
                )
            else:
                conn_str = (
                    f"DRIVER={{{driver}}};"
                    f"SERVER={SQL_SERVER};"
                    f"DATABASE={SQL_DATABASE};"
                    f"UID={SQL_USERNAME};"
                    f"PWD={SQL_PASSWORD};"
                )
            conn = pyodbc.connect(conn_str, timeout=15)
            print(f"  Connected using driver: {driver}")
            break
        except pyodbc.Error:
            continue

    if conn is None:
        raise RuntimeError(
            "Could not connect to SQL Server. "
            "Check server name, credentials, and that an ODBC driver is installed.\n"
            "Install: https://learn.microsoft.com/en-us/sql/connect/odbc/download-odbc-driver-for-sql-server"
        )

    df = pd.read_sql(SQL_QUERY, conn, dtype=str)
    conn.close()
    df["RECORD_TYPE"] = ""
    print(f"  Loaded {len(df):,} rows.")
    return df


def load_from_excel(path: str) -> pd.DataFrame:
    """
    Read the Subscribers and VIP tabs from the supplemental Excel workbook.
    Each row gets a RECORD_TYPE of 'SUBSCRIBER' or 'VIP'.
    Columns are renamed to match the SQL schema where needed.
    Returns a combined DataFrame (Subscribers + VIPs).
    """
    # Map spreadsheet column names → SQL column names used before process() renames them.
    # The spreadsheet uses: OwnerName, street, city, state, zip
    COL_ALIASES = {
        "street": "OwnerStreet",
        "city":   "OwnerCity",
        "state":  "OwnerState",
        "zip":    "OwnerZip",
    }
    frames = []
    for tab, label in [("Subscribers", "SUBSCRIBER"), ("VIP", "VIP")]:
        try:
            tab_df = pd.read_excel(path, sheet_name=tab, dtype=str)
        except Exception as e:
            print(f"  Warning: could not read tab '{tab}' from {path}: {e}")
            continue
        tab_df = tab_df.rename(columns=COL_ALIASES)
        tab_df["RECORD_TYPE"] = label
        frames.append(tab_df)
        print(f"  Loaded {len(tab_df):,} rows from '{tab}' tab.")

    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def combine_sources(sql_df: pd.DataFrame, excel_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge SQL records with Subscriber/VIP records.
    Deduplication happens later in dedup_across_sources(), after process() has
    fully standardized all address fields for every source equally.
    """
    if excel_df.empty:
        return sql_df

    combined = pd.concat([sql_df, excel_df], ignore_index=True)
    return combined.fillna("").reset_index(drop=True)


def dedup_across_sources(df: pd.DataFrame) -> pd.DataFrame:
    """
    Remove VIP/Subscriber rows that duplicate a SQL record, using the fully
    standardized STD_STREET + STD_ZIP key produced by process().

    Priority: SQL record (RECORD_TYPE == "") beats VIP beats SUBSCRIBER.
    If two rows of the same source share a key, the first is kept.
    All sources go through identical standardization before this runs.
    """
    priority = {"": 0, "VIP": 1, "SUBSCRIBER": 2}
    df = df.copy()
    df["_priority"] = df["RECORD_TYPE"].map(priority).fillna(2).astype(int)

    key = df["STD_STREET"] + "|" + df["STD_ZIP"]
    df["_dedup_key"] = key

    df = df.sort_values("_priority")
    df = df[~df["_dedup_key"].duplicated(keep="first")]
    df = df.drop(columns=["_dedup_key", "_priority"])

    sql_count = (df["RECORD_TYPE"] == "").sum()
    sub_count = (df["RECORD_TYPE"] == "SUBSCRIBER").sum()
    vip_count = (df["RECORD_TYPE"] == "VIP").sum()
    print(f"  After cross-source dedup: {sql_count:,} SQL  |  {vip_count:,} VIP  |  {sub_count:,} Subscriber")
    return df.reset_index(drop=True)

