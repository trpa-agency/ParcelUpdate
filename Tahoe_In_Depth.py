def _style_sheet(ws, is_deduped: bool = False):
    """Apply consistent formatting to any worksheet."""
    col_headers = [ws.cell(1, c).value for c in range(1, ws.max_column + 1)]
    status_col  = next((i+1 for i, h in enumerate(col_headers) if h == "STATUS"),       None)
    dupe_col    = next((i+1 for i, h in enumerate(col_headers) if h == "IS_DUPLICATE"),  None)

    # Header row
    for c_idx in range(1, ws.max_column + 1):
        cell = ws.cell(1, c_idx)
        cell.font      = HEADER_FONT
        cell.fill      = HEADER_FILL
        cell.alignment = CENTER_ALIGN
        cell.border    = THIN_BORDER

    # Data rows
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        status_val = ws.cell(row[0].row, status_col).value or "" if status_col else ""
        dupe_val   = ws.cell(row[0].row, dupe_col).value   or "" if dupe_col   else ""
