def process(df: pd.DataFrame) -> pd.DataFrame:
    # Rename SQL columns to internal names
    df = df.rename(columns={
        "OwnerStreet": "street",
        "OwnerCity":   "city",
        "OwnerState":  "state",
        "OwnerZip":    "zip",
    })

    # Normalize ALL columns: trim, collapse whitespace, uppercase
    for col in df.columns:
        df[col] = df[col].apply(clean_str)

    # ── Manual city corrections (before validation and dupe detection) ──
    if "city" in df.columns:
        df["city"] = df["city"].apply(apply_city_correction)

    # ── Owner name C/O cleanup (before dupe detection) ──────────────────
    if "OwnerName" in df.columns:
        df["OwnerName"] = df["OwnerName"].apply(clean_owner_name)

    results = []
    for _, row in df.iterrows():
        street = row.get("street", "")
        city   = row.get("city",   "")
        state  = row.get("state",  "")
        zip_   = row.get("zip",    "")

        status, reason = validate_row(street, city, state, zip_)

        std_street = standardize_street(street) if street else ""
        std_city   = standardize_city(city)     if city   else ""
        std_state  = standardize_state(state)   if state  else ""
        std_zip    = standardize_zip(zip_)       if zip_   else ""

        # Split street into physical address and PO BOX components
        std_street1, std_street2 = split_street(std_street)

        # Apply ZIP-to-city override AFTER standardizing both fields
        std_city, zip_city_note = apply_zip_city_override(std_city, std_zip)

        street_for_full = std_street2 if std_street2 else std_street1
        parts = [p for p in [street_for_full, std_city,
                              f"{std_state} {std_zip}".strip()] if p]

        results.append({
            "STD_STREET":       std_street,
            "STD_STREET1":      std_street1,
            "STD_STREET2":      std_street2,
            "STD_CITY":         std_city,
            "STD_STATE":        std_state,
            "STD_ZIP":          std_zip,
            "STD_FULL_ADDRESS": ", ".join(parts),
            "STATUS":           status,
            "REASON":           reason,
            "CITY_OVERRIDE":    zip_city_note,
        })

    out = pd.concat(
        [df.reset_index(drop=True), pd.DataFrame(results)],
        axis=1
    )
    return flag_duplicates(out)


